package com.venera.compose.gallery.data

/**
 * pixiv 的**可见性档**，也就是站方那枚 `restrict` 查询参数的两个取值。
 *
 * ## 为什么是一枚枚举而不是一串字面量
 *
 * 这一枚以前在 [PixivAppClient] 里写死成 `"public"`（书签腿与关注腿各一处）。
 * pixiv 个人账号页要读**号主自己的非公开那一档**（2026-10-19 拍板），于是它必须变成形参 ——
 * 而形参一旦是 `String`，"某处漏传 / 传成 `"Private"` 大写首字母" 这类错**编译期看不出来、
 * 运行期只表现为站方默默按公开答**（那一屏少了一批内容却一句不吭，正是本仓反复立案的假读数那一族）。
 * 枚举 + 必填（**故意不给默认值**）让每个调用点都被编译器逼着表一次态。
 *
 * ## 私密那一档的边界（改这一枚的用法前先读）
 *
 * `Private` 只在**读号主自己**的书签 / 关注时才有意义。摆到"看别人的画师页收藏"那种调用点上，
 * 站方要么回空要么回 403 —— 所以那种地方必须传 [Public]，不是"随便传一个"。
 * 屏上那一档也从不静默合并：非公开的内容只在账号页选了非公开时才出现，
 * 首页、收藏 hub、分享出去的读数里都不含它。
 */
enum class PixivRestrict(val param: String) {
    /** 公开（站方默认那一档，也是唯一"看别人"时合法的一档）。 */
    Public("public"),

    /** 号主自己标为非公开的那一份。 */
    Private("private"),
}
