package com.venera.compose.gallery.domain

/**
 * 「画成水彩」这一枚入口今天**只住一处**：大图页「关于这张图」面板底部那条动作条。
 *
 * ## 为什么从底栏搬走
 *
 * 那条 dock 在 360dp 上量过：可用内宽 328dp，加回这一枚就是 **7 个 48dp 槽 + 6 条 2dp 间距 = 348dp，
 * 超出 20dp** —— 排不下、最后一枚被圆角裁掉（评审原文写"只剩约 12dp 余量"，那个数少算了一格：
 * 连播那颗 Box 也是 48dp 槽）。撤掉之后 6 槽 = 298dp，余 30dp。低频实验件占高频位不值。
 *
 * ## 为什么这是一颗纯函数而不是就地两个 `if`
 *
 * 这一枚的可见性有**两个**独立否决者：Beta 开关（默认关）与"这一张是视频"。
 * 摆在调用点就是两处各写一遍同样的布尔组合，而这两处会各自漂 —— 漂错的后果是
 * "开关开着但某一档根本点不到"或反过来"视频上也摆了一枚画不出东西的钮"，
 * 两种都没有报错。收成一颗之后判据能真跑四格真值表。
 *
 * 视频那一档的理由沿用底栏时代那条：视频条目取的是 poster 静帧，
 * 用户在一段视频上点「画成水彩」期待的不是把海报画一遍。
 */
internal fun watercolorEntryVisible(betaEnabled: Boolean, isVideo: Boolean): Boolean =
    betaEnabled && !isVideo
