package com.venera.compose.gallery.domain

/**
 * 首页底部那条墙**当前装的是哪一批**。
 *
 * 从前它是 pager 的第 0 / 第 1 页（左右滑切换）。合一屏之后没有第二页了：这一屏自上而下是
 * 几节横卡 + 一条瀑布流，而那条瀑布流是个**可切换的详情区** —— 节点头上的「查看全部」
 * 决定它此刻装日榜全量还是推荐全量（用户 2026-09-30 拍板）。
 *
 * 所以这一枚类型的职责只是"详情区现在给谁让位"，不是"第几页"：
 * - 两批数据各自持有一把网格状态，切换天然不丢各自的滚动位置；
 * - 「换一批 / 刷新」必须按它分发（绑两批的并集会出"已经加载好了还在转"和第二枚环）；
 * - 默认 [DAILY]：冷启动那一屏该是先出货的那一批。
 */
enum class GalleryWallFeed(val label: String) {
    /** 两站上一天的热门合成（一屏到底，没有翻页）。 */
    DAILY("每日热门"),

    /** 按收藏标签抽出来的推荐（有翻页）。 */
    FOR_YOU("猜你喜欢"),
}
